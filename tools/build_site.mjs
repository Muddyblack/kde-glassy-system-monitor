function load(file, globals = {}) {
    const code = fs.readFileSync(path.join(ui, file), "utf8").replace(/^\.(pragma|import).*$/gm, "");
    const context = vm.createContext({ ...globals });
    vm.runInContext(code, context);
    return context;
}
