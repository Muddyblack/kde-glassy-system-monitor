// The studio's own libraries for the browser studio: each .pragma library
// becomes a global namespace with its .imports passed in.
const libraries = [
    ["Catalog", "studio/StudioCatalog.js", []],
    ["Sections", "Sections.js", []],
    ["Format", "Format.js", []],
    ["Data", "diagram/DiagramData.js", []],
    ["DemoData", "DemoData.js", []],
    ["Probes", "Probes.js", []],
    ["SectionModels", "SectionModels.js", [["Sections", "Sections"], ["Format", "Format"], ["DiagramData", "Data"]]],
    ["Looks", "studio/Looks.js", []],
    ["Schema", "studio/Schema.js", [["Catalog", "Catalog"], ["Sections", "Sections"]]],
    ["Funding", "studio/ProjectFunding.js", []],
    ["License", "studio/ProjectLicense.js", []],
    ["Version", "studio/ProjectVersion.js", []],
    ["Project", "studio/ProjectInfo.js", [["Funding", "Funding"], ["License", "License"], ["Version", "Version"]]]
];
const modules = libraries.map(([name, file, imports]) => {
    const code = fs.readFileSync(path.join(ui, file), "utf8").replace(/^\.(pragma|import).*$/gm, "");
    const names = [...code.matchAll(/^(?:var|function)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1]);
    const params = imports.map(i => i[0]).join(", ");
    const args = imports.map(i => "Glassy." + i[1]).join(", ");
    return `// ${file}\nGlassy.${name} = (function (${params}) {\n${code}\nreturn { ${[...new Set(names)].join(", ")} };\n})(${args});`;
}).join("\n\n");
// DiagramData.js asks QML's Qt.color for colour channels.
const qtShim = `var Qt = { color: function (c) {
    var s = String(c).replace("#", ""), a = 1;
    if (s.length === 3) s = s.split("").map(function (x) { return x + x; }).join("");
    if (s.length === 8) { a = parseInt(s.slice(0, 2), 16) / 255; s = s.slice(2); }
    var n = parseInt(s, 16);
    return { r: (n >> 16 & 255) / 255, g: (n >> 8 & 255) / 255, b: (n & 255) / 255, a: a };
} };`;
fs.mkdirSync(path.join(site, "studio"), { recursive: true });
fs.writeFileSync(path.join(site, "studio/shared.js"), `// Generated by tools/build_site.mjs from package/contents/ui. Do not edit.\n${qtShim}\nvar Glassy = {};\n${modules}\nGlassy.defaults = ${JSON.stringify(defaults)};\n`);

// The fragment shader as WebGL runs it: qsb's GLSL ES 100 variant.
const qsbFile = path.join(root, "package/contents/shaders/diagram.frag.qsb");
const esFile = path.join(site, "studio/diagram.frag");
try {
    const dump = execFileSync("qsb", ["--dump", qsbFile], { encoding: "utf8", maxBuffer: 1 << 24 });
    // qsb --dump prints each variant after a "Contents:" line and ends it
    // with a row of asterisks.
    const start = dump.indexOf("#version 100");
    const es = dump.slice(start).split("\n").reduce((acc, line) => acc.done || /^\*{5,}/.test(line) ? { ...acc, done: true } : { lines: acc.lines.concat([line]) }, { lines: [] }).lines.join("\n");
    fs.writeFileSync(esFile, es.trim() + "\n");
} catch (error) {
    if (!fs.existsSync(esFile))
        throw new Error("qsb is needed once to extract the shader: run make docs in the dev shell");
    console.log("docs: qsb not found, keeping " + path.relative(root, esFile));
}

// Wallpapers for the stage and preset cards, from the studio catalogue.
// QML writes #AARRGGBB, CSS reads #RRGGBBAA.
const cssColor = v => /^#[0-9a-f]{8}$/i.test(v) ? "#" + v.slice(3) + v.slice(1, 3) : v;
const theme = Object.entries(Catalog.StudioCatalog.theme).filter(([k]) => k !== "fontFamily").map(([k, v]) => `--studio-${k}:${cssColor(v)}`).join(";");
const wallpapers = Catalog.StudioCatalog.wallpapers.map(w => `.bd-${w.id}{background-color:${w.color};background-image:url("wallpapers/${w.file}")}`).join("\n");
fs.mkdirSync(path.join(site, "assets/studio/wallpapers"), { recursive: true });
fs.writeFileSync(path.join(site, "assets/studio/wallpapers.css"), `/* Generated by tools/build_site.mjs from the studio catalogue. */\n.bd{background-size:cover;background-position:center;background-repeat:no-repeat}\n:root{${theme}}\n${wallpapers}\n`);
for (const w of Catalog.StudioCatalog.wallpapers)
    fs.copyFileSync(path.join(ui, "studio/wallpapers", w.file), path.join(site, "assets/studio/wallpapers", w.file));
fs.copyFileSync(path.join(root, "package/icon.png"), path.join(site, "assets/studio/icon.png"));
fs.writeFileSync(path.join(site, "index.html"), html);
console.log("docs: wrote docs/website (index.html, studio/shared.js, studio/diagram.frag, wallpapers)");
